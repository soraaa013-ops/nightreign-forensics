"""Generate the small search dictionary. Requires pypinyin==0.55.0 (MIT)."""
import json
from pathlib import Path
from pypinyin import pinyin, Style
ROOT = Path(__file__).resolve().parents[1]
text = (ROOT / 'data/zh-CN.json').read_text() + (ROOT / 'src/search.js').read_text()
chars = sorted(set(c for c in text if '\u4e00' <= c <= '\u9fff'))
initials = {c: ''.join(sorted(set(pinyin(c, style=Style.FIRST_LETTER, heteronym=True)[0]))) for c in chars}
(ROOT / 'src/search-initials.js').write_text('// Generated by tools/build-search-initials.py; pypinyin 0.55.0 (MIT).\nexport const initials = ' + json.dumps(initials, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'{len(chars)} characters')
